package main.java.ru.clevertec.check;

public class Discount {
    private int number;
    private int discount;

    public Discount(int number, int discount) {
        this.number = number;
        this.discount = discount;
    }
    public int getNumber() {
        return number;
    }

    public int getDiscount() {
        return discount;
    }
}
